COMMENT ON COLUMN esejur.codigo_verificacion_correo.modificado_en IS 'Fecha y hora de la ultima modificacion del registro.';

CREATE TABLE IF NOT EXISTS token_recuperacion_acceso (
    token_recuperacion_id bigint GENERATED BY DEFAULT AS IDENTITY,
