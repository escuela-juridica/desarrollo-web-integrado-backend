CREATE TABLE IF NOT EXISTS curso (
    curso_id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    curso_origen_id          bigint,
    url_amigable             varchar(180) NOT NULL,
    titulo                   varchar(220) NOT NULL,
    descripcion              text,
    imagen_portada_url       text,
    tipo_curso_id            bigint,
    categoria_tematica_id    bigint,
    entidad_certificadora_id bigint,
    modalidad                varchar(15),
    tipo_venta               varchar(10),
    estado_curso_id          bigint NOT NULL,
    destacado                boolean NOT NULL DEFAULT false,
    precio_regular           numeric(10,2) NOT NULL DEFAULT 0,
    precio_promocional       numeric(10,2),
    promocion_inicio_en      timestamptz,
    promocion_fin_en         timestamptz,
    fecha_inicio             date,
    fecha_fin                date,
    fecha_cierre_matricula   date,
    cupo_maximo              integer,
    horas_academicas         numeric(8,2),
    beneficios               text[] NOT NULL DEFAULT ARRAY[]::text[],
    creado_por_usuario_id    bigint,
    publicado_en             timestamptz,
    cerrado_en               timestamptz,
    cancelado_en             timestamptz,
    creado_en                timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modificado_en            timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_curso PRIMARY KEY (curso_id),
    CONSTRAINT uq_curso_url_amigable UNIQUE (url_amigable),
    CONSTRAINT fk_curso_origen
        FOREIGN KEY (curso_origen_id) REFERENCES curso(curso_id),
    CONSTRAINT fk_curso_tipo
        FOREIGN KEY (tipo_curso_id) REFERENCES tipo_curso(tipo_curso_id),
    CONSTRAINT fk_curso_categoria
        FOREIGN KEY (categoria_tematica_id) REFERENCES categoria_tematica(categoria_tematica_id),
    CONSTRAINT fk_curso_entidad_certificadora
        FOREIGN KEY (entidad_certificadora_id)
        REFERENCES entidad_certificadora(entidad_certificadora_id),
    CONSTRAINT fk_curso_estado
        FOREIGN KEY (estado_curso_id) REFERENCES estado_curso(estado_curso_id),
    CONSTRAINT fk_curso_creado_por
        FOREIGN KEY (creado_por_usuario_id) REFERENCES usuario(usuario_id)
);

